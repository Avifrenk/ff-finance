-- Migration: backfill_default_categories
-- =============================================================================
-- Триггер on_household_created из предыдущей миграции сработает только для
-- новых households. У уже созданных (например «Frenkel» из Фазы 1)
-- категорий нет. Прогоняем seed для всех существующих household.
-- Функция идемпотентна — повторный запуск ничего не сломает.
-- =============================================================================

do $$
declare
  h_id uuid;
begin
  for h_id in select id from public.households loop
    perform public.seed_default_categories(h_id);
  end loop;
end $$;
